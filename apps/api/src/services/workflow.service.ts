export async function listWorkflows(userId: string, q: PaginationQuery & { status?: string }) {
  const ctx = await resolveUserContext(userId);
  const where: any = { organizationId: ctx.organizationId, deletedAt: null };
  if (q.status) where.status = q.status;
  const [items, total] = await Promise.all([
    prisma.workflow.findMany({
      where, orderBy: { updatedAt: "desc" },
      skip: (q.page - 1) * q.perPage, take: q.perPage,
      include: { createdBy: { include: { profile: true } }, _count: { select: { runs: true } } },
    }),
    prisma.workflow.count({ where }),
  ]);
  return {
    items: items.map((w: any) => ({
      id: w.id, name: w.name, description: w.description,
      status: w.status.toLowerCase(),
      triggers: w.triggers, settings: w.settings,
      runsCount: w._count.runs,
      lastRunAt: w.lastRunAt,
      successCount: w.successCount, failureCount: w.failureCount,
      createdBy: { id: w.createdBy.id, displayName: w.createdBy.profile?.displayName ?? w.createdBy.email },
      createdAt: w.createdAt, updatedAt: w.updatedAt,
    })),
    pagination: { page: q.page, perPage: q.perPage, total, totalPages: Math.ceil(total / q.perPage) },
  };
}

