// Lazy import to avoid circular dependency at module load; emit to webhooks AND in-process EventBus.
function dispatch(event: string, orgId: string, payload: Record<string, any>) {
  const full = { ...payload, organizationId: orgId };
  import("./webhook.service.js").then(({ dispatchEvent }) => dispatchEvent(orgId, event, full)).catch(() => {});
  EventBus.emit(event, full).catch(() => {});
}

