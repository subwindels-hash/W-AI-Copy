// ─── Schema ─────────────────────────────────────────────────────
export const NodeShape = z.object({
  id: z.string().min(1),
  type: z.enum(["TRIGGER", "ACTION", "AI", "CONDITION", "LOOP", "APPROVAL", "DELAY", "END"]),
  x: z.number().default(0),
  y: z.number().default(0),
  label: z.string().min(1).max(120),
  config: z.record(z.any()).default({}),
});
export type FlowNode = z.infer<typeof NodeShape>;

export const EdgeShape = z.object({
  id: z.string().min(1),
  fromId: z.string().min(1),
  toId: z.string().min(1),
  label: z.string().optional(),
  condition: z.string().optional(), // e.g. "true" / "false"
});
export type FlowEdge = z.infer<typeof EdgeShape>;

