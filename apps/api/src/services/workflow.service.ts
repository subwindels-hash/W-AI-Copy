// ─── Helpers ────────────────────────────────────────────────────
function topo(nodes: FlowNode[], edges: FlowEdge[]): string[] {
  const indeg = new Map<string, number>();
  const adj = new Map<string, string[]>();
  for (const n of nodes) { indeg.set(n.id, 0); adj.set(n.id, []); }
  for (const e of edges) {
    if (!indeg.has(e.fromId) || !indeg.has(e.toId)) continue;
    adj.get(e.fromId)!.push(e.toId);
    indeg.set(e.toId, (indeg.get(e.toId) ?? 0) + 1);
  }
  const queue: string[] = [];
  for (const [id, d] of indeg) if (d === 0) queue.push(id);
  const order: string[] = [];
  while (queue.length) {
    const id = queue.shift()!;
    order.push(id);
    for (const next of adj.get(id) ?? []) {
      indeg.set(next, (indeg.get(next) ?? 1) - 1);
      if (indeg.get(next) === 0) queue.push(next);
    }
  }
  return order;
}

async function executeNode(
  node: FlowNode,
  context: Record<string, any>,
  orgId: string,
  signal: AbortSignal,
): Promise<{ output: any; status: NodeRunStatus; error?: string }> {
  const startedAt = new Date();
  try {
    switch (node.type) {
      case "TRIGGER":
        return { output: context.input ?? {}, status: NodeRunStatus.SUCCEEDED };
      case "END":
        return {
          output: { completed: true, finishedAt: new Date().toISOString() },
          status: NodeRunStatus.SUCCEEDED,
        };
      case "DELAY": {
        const ms = Math.min((node.config.delayMs ?? 1000), 60_000);
        await new Promise((r) => setTimeout(r, ms));
        return { output: { delayed: ms }, status: NodeRunStatus.SUCCEEDED };
      }
      case "ACTION": {
        // Built-in actions: sendMessage, createTask, createActionItem, httpRequest, log
        const action = node.config.action as string;
        switch (action) {
          case "log":
            return { output: { logged: node.config.message ?? "" }, status: NodeRunStatus.SUCCEEDED };
          case "createTask": {
            const title = renderTemplate(String(node.config.title ?? "Workflow task"), context);
            const t = await prisma.task.create({
              data: {
                organizationId: orgId,
                title,
                description: renderTemplate(String(node.config.description ?? ""), context),
                priority: (node.config.priority as any) ?? "MEDIUM",
                agentId: node.config.agentId ?? null,
                creatorId: context.__createdById,
              },
            });
            return { output: { taskId: t.id, title: t.title }, status: NodeRunStatus.SUCCEEDED };
          }
          case "createActionItem": {
            const a = await prisma.actionItem.create({
              data: {
                organizationId: orgId,
                title: renderTemplate(String(node.config.title ?? "Action item"), context),
                description: renderTemplate(String(node.config.description ?? ""), context),
                priority: (node.config.priority as any) ?? "MEDIUM",
                channelId: node.config.channelId ?? null,
                assigneeId: node.config.assigneeId ?? null,
                createdById: context.__createdById,
              },
            });
            return { output: { actionItemId: a.id }, status: NodeRunStatus.SUCCEEDED };
          }
          case "sendMessage": {
            const chId = node.config.channelId as string | undefined;
            if (!chId) throw AppError.badRequest("sendMessage requires channelId");
            const content = renderTemplate(String(node.config.message ?? "(workflow message)"), context);
            const msg = await prisma.talkMessage.create({
              data: { channelId: chId, type: "TEXT" as any, content, userId: context.__createdById },
            });
            await prisma.talkChannel.update({ where: { id: chId }, data: { lastMessageAt: new Date() } });
            return { output: { messageId: msg.id }, status: NodeRunStatus.SUCCEEDED };
          }
          case "httpRequest": {
            const url = String(node.config.url ?? "");
            if (!url) throw AppError.badRequest("httpRequest requires url");
            const method = String(node.config.method ?? "GET").toUpperCase();
            const headers: Record<string, string> = { "Content-Type": "application/json" };
            if (node.config.headers) Object.assign(headers, node.config.headers);
            let body: string | undefined;
            if (method !== "GET" && node.config.body) body = JSON.stringify(renderObject(node.config.body, context));
            const resp = await fetch(url, { method, headers, body, signal });
            const text = await resp.text();
            let json: any = undefined;
            try { json = JSON.parse(text); } catch { json = text; }
            if (!resp.ok) return { output: { status: resp.status, body: json }, status: NodeRunStatus.FAILED, error: `HTTP ${resp.status}` };
            return { output: { status: resp.status, body: json }, status: NodeRunStatus.SUCCEEDED };
          }
          default:
            return { output: { note: `No-op action: ${action ?? "none"}` }, status: NodeRunStatus.SUCCEEDED };
        }
      }
      case "AI": {
        const modelId = node.config.modelId as string | undefined;
        const resolved = aiRegistry.resolve(modelId);
        if (!resolved) {
          return { output: { error: "AI PROVIDER CONFIGURATION REQUIRED" }, status: NodeRunStatus.FAILED };
        }
        const sys = node.config.systemPrompt as string | undefined
          ?? `You are a workflow AI node. Execute the instruction using the provided context and return JSON only.`;
        const prompt = renderTemplate(String(node.config.prompt ?? node.label), context);
        let out = "";
        for await (const chunk of aiRegistry.guardedStream({
          model: resolved.model.id,
          messages: [
            { role: "system", content: sys },
            { role: "user", content: `${prompt}\n\nContext: ${JSON.stringify(context).slice(0, 4000)}` },
          ],
          stream: true,
          signal,
        }, { userId: context.__createdById, feature: "workflow-ai-node" })) {
          if (chunk.type === "token") out += chunk.text ?? "";
        }
        // Try parse JSON; fall back to raw string
        let parsed: any = out.trim();
        try { parsed = JSON.parse(out); } catch { /* keep string */ }
        return { output: { result: parsed, raw: out }, status: NodeRunStatus.SUCCEEDED };
      }
      case "CONDITION": {
        const expr = String(node.config.expr ?? "true");
        // Safe-ish condition eval: only supports equality + truthy on context paths.
        const result = evalCondition(expr, context);
        return { output: { result }, status: NodeRunStatus.SUCCEEDED };
      }
      case "LOOP": {
        const over = resolvePath(context, String(node.config.collectionPath ?? "items")) ?? [];
        const items = Array.isArray(over) ? over : [];
        const results: any[] = [];
        const maxItems = Math.min(items.length, 20);
        for (let i = 0; i < maxItems; i++) results.push({ index: i, item: items[i] });
        return { output: { iterations: results, count: results.length }, status: NodeRunStatus.SUCCEEDED };
      }
      case "APPROVAL": {
        // In MVP this pauses the run waiting on human. For synchronous execution in this slice we
        // treat it as immediately approved unless settings.autoApprove is false, in which case we
        // mark the run as WAITING_APPROVAL.
        if (node.config.requireHuman) {
          return { output: { approved: false, pending: true }, status: NodeRunStatus.WAITING_APPROVAL };
        }
        return { output: { approved: true }, status: NodeRunStatus.SUCCEEDED };
      }
      default:
        return { output: null, status: NodeRunStatus.SKIPPED };
    }
  } catch (err: any) {
    return { output: null, status: NodeRunStatus.FAILED, error: err?.message ?? String(err) };
  } finally {
    void startedAt;
  }
}

function evalCondition(expr: string, ctx: any): boolean {
  // Tiny, sandboxed condition: supports "a.b == 'x'", "a.b", "a.b > 2", "true", "false".
  const m = expr.match(/^([\w.]+)\s*(==|!=|>=|<=|>|<)\s*(.+)$/);
  if (!m) return !!resolvePath(ctx, expr);
  const [, path, op, rawVal] = m;
  const left = resolvePath(ctx, path!);
  let right: any = rawVal!.trim();
  if ((right.startsWith("'") && right.endsWith("'")) || (right.startsWith('"') && right.endsWith('"'))) right = right.slice(1, -1);
  else if (!isNaN(Number(right))) right = Number(right);
  else if (right === "true") right = true;
  else if (right === "false") right = false;
  switch (op) {
    case "==": return left == right;
    case "!=": return left != right;
    case ">": return Number(left) > Number(right);
    case "<": return Number(left) < Number(right);
    case ">=": return Number(left) >= Number(right);
    case "<=": return Number(left) <= Number(right);
  }
  return false;
}

function resolvePath(obj: any, path: string): any {
  return path.split(".").reduce((acc, k) => (acc == null ? acc : acc[k]), obj);
}

function renderTemplate(tmpl: string, ctx: any): string {
  return tmpl.replace(/\{\{\s*([\w.]+)(?:\s*\|[^}]*)?\s*\}\}/g, (_m, p) => {
    const v = resolvePath(ctx, p);
    return v == null ? "" : String(v);
  });
}
function renderObject(obj: any, ctx: any): any {
  if (typeof obj === "string") return renderTemplate(obj, ctx);
  if (Array.isArray(obj)) return obj.map((v) => renderObject(v, ctx));
  if (obj && typeof obj === "object") {
    const out: Record<string, any> = {};
    for (const [k, v] of Object.entries(obj)) out[k] = renderObject(v, ctx);
    return out;
  }
  return obj;
}

