// ─── Execution ──────────────────────────────────────────────────
/**
 * Run a workflow. With `organizationId` omitted (the default) the workflow
 * is resolved through the actor's membership — the historical behaviour.
 *
 * Session 120 — the public API gateway passes the *API key's* organization
 * explicitly. Before that, the public route called this with only the key
 * creator's user id, so the workflow was resolved through the creator's
 * membership: a key issued to org A whose creator also belonged to org B
 * could trigger org B's workflows — a cross-tenant hole on the public
 * surface. With the organization pinned, the lookup cannot leave the key's
 * tenant, and the actor's membership is not consulted at all.
 */
export async function runWorkflow(userId: string, id: string, input: z.infer<typeof RunWorkflowSchema>, organizationId?: string) {
  const ctx = organizationId ? null : await resolveUserContext(userId);
  const orgId = organizationId ?? ctx!.organizationId;
  const w = await prisma.workflow.findFirst({ where: { id, organizationId: orgId, deletedAt: null } });
  if (!w) throw AppError.notFound("Workflow not found");
  if (w.status !== WorkflowStatus.ACTIVE && w.status !== WorkflowStatus.DRAFT) {
    throw AppError.badRequest(`Workflow is ${w.status.toLowerCase()}; cannot run.`);
  }
  const nodes = (w.nodes as any as FlowNode[]);
  const edges = (w.edges as any as FlowEdge[]);
  const settings = (w.settings as any) ?? {};

  // Build a run record
  const run = await prisma.workflowRun.create({
    data: {
      workflowId: id,
      triggerType: input.triggerType,
      triggerData: input.triggerData as any,
      status: WorkflowRunStatus.RUNNING,
      startedAt: new Date(),
      input: { ...input.input, __createdById: userId, __workflowId: id } as any,
      createdById: userId,
    },
  });

  const order = topo(nodes, edges);
  const nodeMap = new Map(nodes.map((n) => [n.id, n]));
  const outs = new Map<string, any>();
  outs.set("__input", input.input);
  const nodeRuns: any[] = [];
  let status: WorkflowRunStatus = WorkflowRunStatus.SUCCEEDED;
  let error: string | null = null;
  const controller = new AbortController();

  const startNode = nodes.find((n) => n.type === "TRIGGER") ?? nodes[0];
  const context: Record<string, any> = { ...input.input, __createdById: userId, __workflowId: id };

  // Follow edges starting from startNode; traverse in BFS order honoring conditions
  const visited = new Set<string>();
  const queue: string[] = startNode ? [startNode.id] : order;
  while (queue.length) {
    const nid = queue.shift()!;
    if (visited.has(nid)) continue;
    visited.add(nid);
    const node = nodeMap.get(nid);
    if (!node) continue;
    const retryCount = Math.max(0, Number(settings.retryCount ?? 1));
    let lastResult: any = null;
    for (let attempt = 0; attempt <= retryCount; attempt++) {
      const t0 = Date.now();
      const res = await executeNode(node, context, orgId, controller.signal);
      nodeRuns.push({
        nodeId: node.id, label: node.label, type: node.type,
        status: res.status, attempts: attempt + 1, durationMs: Date.now() - t0,
        output: res.output, error: res.error ?? null,
      });
      lastResult = res;
      if (res.status === NodeRunStatus.SUCCEEDED) {
        // put node output on context keyed by node id
        context[node.id] = res.output;
        outs.set(node.id, res.output);
        // Find outgoing edges
        const out = edges.filter((e) => e.fromId === node.id);
        for (const e of out) {
          if (node.type === "CONDITION") {
            const branchMatches = String(e.condition ?? "true").trim().toLowerCase() === String(!!res.output?.result).toLowerCase();
            if (!branchMatches && !(e.condition == null)) continue;
          }
          queue.push(e.toId);
        }
        break;
      } else if (res.status === NodeRunStatus.WAITING_APPROVAL) {
        status = WorkflowRunStatus.WAITING_APPROVAL;
        await prisma.workflowRun.update({
          where: { id: run.id },
          data: { status, nodeRuns: nodeRuns as any, output: outs.get("__input") as any },
        });
        return { runId: run.id, status: "waiting_approval", nodeRuns };
      } else if (attempt < retryCount) {
        await new Promise((r) => setTimeout(r, Number(settings.retryDelayMs ?? 1000)));
      } else {
        status = WorkflowRunStatus.FAILED;
        error = res.error ?? `Node "${node.label}" failed`;
        await prisma.workflow.update({
          where: { id },
          data: {
            failureCount: { increment: 1 },
            lastRunAt: new Date(),
            runsCount: { increment: 1 },
          },
        });
        await prisma.workflowRun.update({
          where: { id: run.id },
          data: { status, endedAt: new Date(), error, nodeRuns: nodeRuns as any, output: outs.get("__input") as any },
        });
        dispatch("workflow.run.failed", orgId, { workflowId: id, workflowName: w.name, runId: run.id, error });
        throw new AppError("INTERNAL_ERROR", error ?? `Node "${node.label}" failed`, 500);
      }
    }
    void lastResult;
  }

  await prisma.workflow.update({
    where: { id },
    data: {
      successCount: { increment: 1 },
      runsCount: { increment: 1 },
      lastRunAt: new Date(),
    },
  });
  await prisma.workflowRun.update({
    where: { id: run.id },
    data: { status, endedAt: new Date(), nodeRuns: nodeRuns as any, output: outs as any },
  });
  dispatch("workflow.run.succeeded", orgId, { workflowId: id, workflowName: w.name, runId: run.id });
  return { runId: run.id, status: "succeeded", nodeRuns };
}

export async function approveRun(userId: string, runId: string, approved: boolean, feedback?: string) {
  const ctx = await resolveUserContext(userId);
  const run = await prisma.workflowRun.findFirst({
    where: { id: runId }, include: { workflow: true },
  });
  if (!run || run.workflow.organizationId !== ctx.organizationId) throw AppError.notFound("Run not found");
  if (run.status !== WorkflowRunStatus.WAITING_APPROVAL) throw AppError.badRequest("Run not awaiting approval");
  await prisma.workflowRun.update({
    where: { id: runId },
    data: {
      status: approved ? WorkflowRunStatus.RUNNING : WorkflowRunStatus.CANCELLED,
      output: { ...(run.output as any), __approval: { approved, feedback } } as any,
      endedAt: approved ? null : new Date(),
    },
  });
  return { ok: true };
}

